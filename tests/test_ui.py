            check("stacked copies", "All 3: 3.00 in wide" in pg.inner_text("#dims"), pg.inner_text("#dims"))
            pg.click("#lay-across")
            pg.wait_for_function("document.querySelector('#dims').innerText.includes('(3 across)')")

            pg.click("#cut")
